# ---------- 工具：确定性随机 ----------
def det_rand(seed_str, lo, hi):
    h = int(hashlib.md5(seed_str.encode()).hexdigest()[:8], 16)
    rnd = random.Random(h)
    return rnd.randint(lo, hi)

def det_choice(seed_str, arr):
    h = int(hashlib.md5(seed_str.encode()).hexdigest()[:8], 16)
    rnd = random.Random(h+1)
    return rnd.choice(arr)

