def gen_example(name, domain, grade, tid):
    # 根据年级生成一个简单例题
    a = det_rand(tid+"a", 2, 9)
    b = det_rand(tid+"b", 2, 9)
    c = a + b
    if domain == "数与代数":
        if grade <=2:
            prob = f"小明有 {a} 块糖，妈妈又给他 {b} 块，现在一共有几块？"
            steps = [f"一共 = 原有 {a} + 又得 {b}", f"{a} + {b} = {c}"]
            ans = f"{c} 块"
        elif grade <=3:
            x = det_rand(tid+"x", 12, 48)
            y = det_rand(tid+"y", 2, 9)
            prob = f"计算：{x} × {y} =？"
            ans_val = x*y
            steps = [f"先算 {x} × {y}", f"={ans_val}"]
            ans = str(ans_val)
        elif grade <=4:
            prob = f"一个长方形长 {a+2} 厘米，宽 {b+1} 厘米，面积是多少？"
            area = (a+2)*(b+1)
            steps = [f"长方形面积 = 长 × 宽", f"= {a+2} × {b+1} = {area} 平方厘米"]
            ans = f"{area} 平方厘米"
        else:
            prob = f"解方程：x + {a} = {c}，求 x"
            steps = [f"x = {c} - {a}", f"x = {b}"]
            ans = f"x={b}"
        return prob, steps, ans
    elif domain == "图形与几何":
        prob = f"判断：长方形的四个角都是直角，对边相等。这句话对吗？"
        steps = ["回顾长方形特征：4个直角，对边相等", "与描述完全一致"]
        ans = "对"
        return prob, steps, ans
    elif domain == "统计与概率":
        prob = f"一组数据：{a}, {b}, {a+3}, 5，平均数是多少？"
        total = a + b + (a+3) + 5
        avg = total / 4
        steps = [f"总和 = {a}+{b}+{a+3}+5 = {total}", f"平均数 = {total} ÷ 4 = {avg}"]
        ans = str(avg)
        return prob, steps, ans
    else:
        prob = f"小商店1瓶水 {a} 元，买 {b} 瓶需要多少钱？"
        steps = [f"总价 = 单价 × 数量", f"= {a} × {b} = {a*b} 元"]
        ans = f"{a*b} 元"
        return prob, steps, ans

