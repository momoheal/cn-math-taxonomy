# 处理缺失的 prereq 名字占位：如“自然数的直观”“分数的初步认识准备”
# 我们创建虚拟映射：若名字不在已有 spec 中，则映射到最接近的外部或已有节点
# 首先建立 name->id 映射（按 specs 顺序生成 id）

# ---------- 构建 topics、deps、questions ----------
topics = []
deps = []
all_questions = []

# 先加入 externals 到 topics
for ext in externals:
    topics.append(ext)

# 建立 name 到 id 的映射（包含外部）
name_to_id = {e["name"]: e["id"] for e in externals}
# 预先分配正式 id：cnm_001 开始按 specs 顺序
for idx, spec in enumerate(specs, 1):
    tid = f"cnm_{idx:03d}"
    name_to_id[spec["name"]] = tid
    # 也支持章节别名映射？暂不需要

# 再逐个生成正式 topic
for idx, spec in enumerate(specs, 1):
    tid = f"cnm_{idx:03d}"
    grade = spec["grade"]
    sem = spec["semester"]
    chap_str = spec["chapter"]
    name = spec["name"]
    domain = spec["domain"]
    ttype = spec["type"]
    desc = spec["description"]
    std_ids = spec["std_ids"]
    prereq_names = spec["prereq_names"]

    # 生成 mastery criteria
    if ttype == "conceptual":
        mastery = [f"能清晰说出“{name}”的含义或特征", f"能在情境中正确辨认或举例说明“{name}”"]
    elif ttype == "procedural":
        mastery = [f"能熟练进行“{name}”的计算或操作，正确率高", f"能在实际问题中正确运用“{name}”列式或画图"]
    elif ttype == "reasoning":
        mastery = [f"能运用“{name}”进行有条理的推理", f"能解释“{name}”的规律或关系，并用语言表达思考过程"]
    elif ttype == "application":
        mastery = [f"能运用“{name}”解决生活中的实际问题", f"能对结果的合理性进行检验和解释"]
    else: # modeling
        mastery = [f"能参与“{name}”的主题活动，完成数据收集与表达", f"能用数学语言描述活动中的发现"]

    # 生成诊断题与辅导
    dq_q, dq_a = gen_dq(name, domain, grade, tid)
    key_points = gen_key_points(name, domain, desc)
    ex_prob, ex_steps, ex_ans = gen_example(name, domain, grade, tid)
    mistakes = gen_mistakes(name, domain)
    tip = gen_tip(name)

    # standards
    standards = []
    for sid in std_ids:
        # 对于需要 note 的 inferred，我们简单标记为 exact（因为我们已按课标分条尽量精确）
        # 若 sid 本身不在我们 64条中，尝试映射到最接近的；但我们已确保所有 std_ids 均在 64条中
        standards.append(std_ref(sid, "exact"))

    # prereqs 转换：名字 -> id，若名字不在映射中，尝试模糊匹配或忽略
    prereqs = []
    for pname in prereq_names:
        # 特殊占位处理
        if pname == "分数的初步认识准备":
            # 指向“小数的意义与性质”之前最近的分数相关，或直接指向“带小括号的四则运算”作为占位
            # 我们改为指向“带小括号的四则运算”
            pname = "带小括号的四则运算"
        if pname == "自然数的直观":
            # 指向“小数的四则混合运算与自然数”
            pname = "小数的四则混合运算与自然数"
        if pname == "入学适应·数学观察":
            # 已存在
            pass
        pid = name_to_id.get(pname)
        if not pid:
            # 尝试外部节点映射
            # 如 “长度比较直观” -> ext
            ext_map = {
                "长度比较直观": "cnm_ext_006",
                "方位与位置直观": "cnm_ext_003",
                "立体图形直观": "cnm_ext_004",
            }
            pid = ext_map.get(pname)
        if pid:
            # 判断 hard/soft：若在同册且是紧邻前驱，设 hard，否则 soft 若是跨册
            # 简化：计算题依赖计算题为 hard，跨领域为 soft
            # 我们根据 domain 是否相同决定
            # 找到 pid 对应 spec 的 domain
            # 外部默认为 hard
            strength = "hard"
            if "复习" in pname or "整理" in pname:
                strength = "soft"
            # 若跨年级，设 soft？但多数应为 hard 以体现基础
            # 我们根据描述关键词
            reason = f"学习“{name}”需要先掌握“{pname}”的基础"
            prereqs.append((pid, strength, reason))
        else:
            print(f"警告：未找到先修 {pname} 对应 {name}")

    # 生成 Questions
    questions = gen_questions(tid, name, domain, grade, dq_q, dq_a)

    topic, dep_list, q_list = make_topic(
        tid, name, domain, grade, sem, chap_str, ttype,
        desc, mastery, dq_q, dq_a,
        standards, key_points, ex_prob, ex_steps, ex_ans,
        mistakes, tip, prereqs, questions
    )
    topics.append(topic)
    deps.extend(dep_list)
    all_questions.extend(q_list)

# ---------- 额外处理：确保每个正式点至少有一个 hard 先修（或 root_reason） ----------
# 我们已保证每个点都有 prereqs；对于极少数遗漏的（如第一单元），应指向外部
# 检查
for t in topics:
    if not t["external"]:
        has_pre = any(d["topicId"]==t["id"] for d in deps)
        if not has_pre:
            # 自动补一条到对应的学前外部
            # 根据 grade/domain 选择
            if t["domain"]=="数与代数":
                pid="cnm_ext_001"
                pname="唱数与点数（1-20）"
            elif t["domain"]=="图形与几何":
                pid="cnm_ext_004"
                pname="立体图形直观"
            elif t["domain"]=="统计与概率":
                pid="cnm_ext_009"
                pname="数据整理直观"
            else:
                pid="cnm_ext_002"
                pname="简单分类与比较"
            deps.append({"topicId": t["id"], "prerequisiteId": pid, "strength": "hard", "reason": f"“{t['name']}”的学习建立在学前“{pname}”的基础上"})

# ---------- 排序与输出 ----------
# topics 保持原顺序（外部在前，正式按年级册次）
# deps 去重
seen = set()
uniq_deps = []
for d in deps:
    key = (d["topicId"], d["prerequisiteId"])
    if key not in seen:
        seen.add(key)
        uniq_deps.append(d)

